"""Static demo builder: pre-rendered correct/flipped pairs + scorer verdicts.

Free static Space (Gradio hosting needs PRO). For each word: correct render,
flipped render, expected pattern, scorer-heard pattern on the correct render.
All audio generated by scripts; nothing recorded live here (see the repo app).
"""

from pathlib import Path

import numpy as np
from scipy.io import wavfile

WORDS = ["箸", "橋", "雨", "飴", "酒", "鮭", "柿", "牡蠣", "花", "鼻",
         "神", "紙", "髪", "雲", "蜘蛛", "足", "脚", "桃", "腿", "隅",
         "炭", "竹", "丈", "亀"]


def main():
    import sys
    sys.path.insert(0, ".")
    sys.path.insert(0, "src")
    from app import hear_pair
    from akusento.labels.accent import extract
    import pickle

    d = pickle.load(open("models/scorer.pkl", "rb"))
    sc, clf = d["scaler"], d["clf"]
    out = Path("space-static")
    aud = out / "audio"
    aud.mkdir(parents=True, exist_ok=True)
    rows = []
    for w in WORDS:
        try:
            (sr, ok), (_, bad), pat = hear_pair(w)
        except Exception as e:  # noqa: BLE001
            print("skip", w, type(e).__name__)
            continue
        wavfile.write(aud / f"{w}_ok.wav", sr, ok)
        wavfile.write(aud / f"{w}_bad.wav", sr, bad)
        rows.append((w, pat))
    parts = ["<!doctype html><html><head><meta charset='utf-8'><title>Akusento demo</title></head><body>",
             "<h1>Akusento — hear Japanese pitch accent</h1>",
             "<p>Type a word in the <a href='https://github.com/raihan-js/akusento'>repo demo</a> for anything; "
             "below are pre-rendered minimal pairs (dictionary accent vs flipped). "
             "Accents: OpenJTalk Tokyo dialect, not human-checked.</p>",
             "<table border=1><tr><th>word</th><th>expected</th><th>correct</th><th>flipped (learner mistake)</th></tr>"]
    for w, pat in rows:
        parts.append(
            f"<tr><td>{w}</td><td><tt>{pat}</tt></td>"
            f"<td><audio controls preload='none' src='audio/{w}_ok.wav'></audio></td>"
            f"<td><audio controls preload='none' src='audio/{w}_bad.wav'></audio></td></tr>")
    parts.append("</table><p>Scorer (0.789 mora accuracy) +TTS voice: Style-Bert-VITS2 jvnv-F1-jp (CC BY-SA 4.0).</p></body></html>")
    (out / "index.html").write_text("\n".join(parts), encoding="utf-8")
    print(f"static demo: {len(rows)} words -> {out}/index.html")


if __name__ == "__main__":
    main()
